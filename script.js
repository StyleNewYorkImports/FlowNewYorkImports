async function destroyCardBrick() {
  if (cardPaymentBrickController && typeof cardPaymentBrickController.unmount === "function") {
    try { await cardPaymentBrickController.unmount(); } catch (_) {}
  }
  cardPaymentBrickController = null;
  cardBrickAmount = null;
}

async function renderMercadoPagoCardBrick() {
  const amount = Number(getTotals().total.toFixed(2));
  if (!amount || !$("cardPaymentBrick_container")) return;

  if (!window.MercadoPago) {
    setCardStatus("error", "Mercado Pago não carregou", "Abra a loja por um servidor HTTPS/localhost e tente novamente.");
    return;
  }

  if (cardPaymentBrickController && cardBrickAmount === amount) return;
  await destroyCardBrick();
  $("cardPaymentBrick_container").innerHTML = "";

  try {
    if (!CONFIG.MP_PUBLIC_KEY) {
      const cfgResponse = await fetch("/api/config", { cache: "no-store" });
      const cfg = await cfgResponse.json();
      if (!cfgResponse.ok || !cfg.publicKey) throw new Error("Pagamento ainda não foi configurado.");
      CONFIG.MP_PUBLIC_KEY = cfg.publicKey;
    }
    mpInstance = mpInstance || new MercadoPago(CONFIG.MP_PUBLIC_KEY, { locale: "pt-BR" });
    const bricksBuilder = mpInstance.bricks();

    const settings = {
      initialization: { amount },
      customization: {
        visual: { style: { theme: "default" } }
      },
      callbacks: {
        onReady: () => setCardStatus("ready", "Pagamento protegido pelo Mercado Pago", "Preencha os dados do cartão para continuar."),
        onSubmit: (formData, additionalData) => new Promise(async (resolve, reject) => {
          try {
            setCardStatus("processing", "Processando pagamento...", "Aguarde a resposta do Mercado Pago.");

            const payload = {
              type: "online",
              total_amount: String(Number(formData.transaction_amount).toFixed(2)),
              external_reference: `SNY-${Date.now()}`,
              processing_mode: "automatic",
              transactions: {
                payments: [{
                  amount: String(Number(formData.transaction_amount).toFixed(2)),
                  payment_method: {
                    id: formData.payment_method_id,
                    type: additionalData.paymentTypeId,
                    token: formData.token,
                    installments: Number(formData.installments || 1)
                  }
                }]
              },
              payer: {
                email: formData.payer.email,
                identification: formData.payer.identification
              },
              store_cart: cart.map(i => ({ id: Number(i.id), qty: Number(i.qty) }))
            };

            const response = await fetch("/process_order", {
              method: "POST",
              headers: { "Content-Type": "application/json" },
              body: JSON.stringify(payload)
            });
            const result = await response.json();

            if (!response.ok) {
              throw new Error(result.message || result.error || "Pagamento não pôde ser processado.");
            }

            const payment = result?.transactions?.payments?.[0];
            const status = payment?.status || result?.status || "";
            const detail = payment?.status_detail || result?.status_detail || "";

            if (status === "processed" && detail === "accredited") {
              setCardStatus("success", "Pagamento aprovado ✓", `Pedido ${result.id || ""}`);
              localStorage.setItem("sny_mp_order", JSON.stringify({ id: result.id, status, detail }));
              toast("Pagamento aprovado pelo Mercado Pago.");
              setTimeout(showDeliveryStep, 900);
            } else if (["processing", "action_required", "created"].includes(status)) {
              setCardStatus("processing", "Pagamento em análise", "A confirmação pode levar alguns instantes. Não tente pagar novamente.");
            } else {
              setCardStatus("error", "Pagamento não aprovado", detail || "Tente outro cartão ou revise os dados.");
            }
            resolve();
          } catch (err) {
            console.error(err);
            setCardStatus("error", "Não foi possível processar", err.message || "Verifique o servidor da loja.");
            reject(err);
          }
        }),
        onError: (error) => {
          console.error("Mercado Pago Brick:", error);
          setCardStatus("error", "Erro no formulário de pagamento", "Confira os dados e tente novamente.");
        }
      }
    };

    cardPaymentBrickController = await bricksBuilder.create("cardPayment", "cardPaymentBrick_container", settings);
    cardBrickAmount = amount;
  } catch (err) {
    console.error(err);
    setCardStatus("error", "Falha ao iniciar o checkout", "Confira a Public Key e execute a loja pelo servidor.");
  }
}

