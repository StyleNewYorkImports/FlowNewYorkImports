function renderProducts(items) {
  const grid = $("productsGrid");
  const empty = $("emptyState");
  if (!grid) return;
  grid.innerHTML = "";
  if (!items.length) {
    if (empty) empty.classList.remove("hidden");
    return;
  }
  if (empty) empty.classList.add("hidden");

  items.forEach(product => {
    const fav = favorites.includes(product.id);
    const discount = product.oldPrice > product.price ? Math.round((1 - product.price / product.oldPrice) * 100) : 0;
    const card = document.createElement("article");
    card.className = "product-card";
    card.innerHTML = `
      <div class="product-image" data-product="${product.id}">
        <span class="product-badge">${product.badge || (discount ? "OFERTA" : "")}</span>
        <button class="fav-card ${fav ? "active" : ""}" data-fav="${product.id}" aria-label="Favoritar">${fav ? "♥" : "♡"}</button>
        <img src="${encodeURI(product.image)}" alt="${escapeHtml(product.name)}" loading="lazy">
      </div>
      <div class="product-info">
        <div class="product-category">${escapeHtml(product.category)}</div>
        <h3 class="product-name">${escapeHtml(product.name)}</h3>
        <div class="price-row">
          <span class="old-price">${money(product.oldPrice)}</span>
          <span class="current-price">${money(product.price)}</span>
          ${discount ? `<span class="discount">-${discount}%</span>` : ""}
        </div>
        <div class="stock-line">🔥 <b>Últimas ${product.stock} unidades</b></div>
        <button type="button" class="product-btn" data-product="${product.id}">Escolher tamanho e cor</button>
      </div>`;
    grid.appendChild(card);
  });
}

function applyFilters() {
  const q = $("searchInput") ? $("searchInput").value.toLowerCase().trim() : "";
  let list = PRODUCTS.filter(p => {
    const matchesFilter = activeFilter === "all" || activeFilter === "PROMOÇÕES" ? true : p.category === activeFilter;
    const matchesSearch = !q || `${p.name} ${p.category}`.toLowerCase().includes(q);
    return matchesFilter && matchesSearch;
  });
  if (activeFilter === "PROMOÇÕES") list = list.filter(p => p.oldPrice > p.price);
  renderProducts(list);
}

